-- 3) Admin helper — avoids recursive RLS checks on profiles
-- ------------------------------------------------------------
create or replace function public.is_chef_noor_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
