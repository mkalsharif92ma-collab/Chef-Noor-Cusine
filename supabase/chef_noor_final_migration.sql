-- Tracking view: intentionally exposes no customer identity/address.
create or replace function public.get_delivery_tracking(p_route_id bigint)
returns table(status text, stop_number integer, eta_minutes integer, driver_latitude double precision, driver_longitude double precision, delivered_stops integer, total_stops integer)
language sql stable security definer set search_path = public
as $$
  with r as (select * from public.delivery_routes where id = p_route_id),
  last_location as (
    select dl.latitude, dl.longitude from public.driver_locations dl join r on r.driver_id=dl.driver_id order by dl.recorded_at desc limit 1
  )
  select coalesce((select ds.status from public.delivery_stops ds where ds.route_id=p_route_id and ds.status <> 'delivered' order by ds.stop_order limit 1),'delivered'),
         coalesce((select ds.stop_order from public.delivery_stops ds where ds.route_id=p_route_id and ds.status <> 'delivered' order by ds.stop_order limit 1),0),
         (select ds.eta_minutes from public.delivery_stops ds where ds.route_id=p_route_id and ds.status <> 'delivered' order by ds.stop_order limit 1),
         (select latitude from last_location),(select longitude from last_location),
         (select count(*)::integer from public.delivery_stops where route_id=p_route_id and status='delivered'),
         (select total_stops from r);
$$;

